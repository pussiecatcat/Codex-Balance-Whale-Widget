import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

export async function verifyFeatureUI({window,ev,wait,dispatcher,output}) {
  const checks=[];
  const screenshot=async name=>{await new Promise(resolve=>setTimeout(resolve,600));fs.writeFileSync(path.join(output,name+'.png'),(await window.webContents.capturePage()).toPNG());};
  const click=async selector=>ev(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const field=async(name,value)=>ev(`(()=>{const input=document.querySelector('dialog.api-model-card [data-field="${name}"]');input.value=${JSON.stringify(value)};input.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  await ev("window.dispatchEvent(new Event('whale-open-settings'))");
  await wait("document.querySelector('#settings-dialog').open",'API settings open');
  await ev("document.querySelector('#api-models-panel').open=true");
  await wait("document.querySelector('#api-models-root button.primary')",'API catalog ready');
  await click('#api-models-root button.primary');
  await wait("document.querySelector('dialog.api-model-card')?.open",'model editor open');
  assert.equal(await ev("document.querySelector('dialog.api-model-card').matches(':modal')"),true);
  assert.equal(await ev("document.querySelector('dialog.api-model-card select[data-field=template]').options.length"),34);
  assert.equal(await ev("(()=>{const e=document.querySelector('dialog.api-model-card input[data-field=name]'),r=e.getBoundingClientRect();return document.elementFromPoint(r.left+r.width/2,r.top+r.height/2)===e;})()"),true);
  await field('name','UI 模型测试');await field('balanceBelow','3');await field('inputPrice','2');await field('cachedPrice','1');await field('outputPrice','10');
  await field('manualTotal','100');await field('manualRemaining','75');await field('manualReset','2030-01-01T00:00');
  await click('dialog.api-model-card .primary');
  await wait("!document.querySelector('dialog.api-model-card')&&document.querySelector('.api-model-meta strong')?.textContent==='UI 模型测试'",'saved model listed');
  let data=JSON.parse((await dispatcher.dispatch('/api/models')).body);
  assert.equal(data.models.length,1);let model=data.models[0];assert.equal(model.prices.cached,1);assert.equal(model.manualQuota.remaining,75);
  checks.push('native model dialog stays above API settings, lists 34 templates, and persists prices, manual quota and alerts');
  await click('.api-model-row button:nth-of-type(2)');
  await wait("document.querySelector('dialog.api-model-card')?.open",'edit model');
  assert.equal(await ev("document.querySelector('dialog.api-model-card input[data-field=manualRemaining]').value"),'75');
  await field('balanceBelow','');await click('dialog.api-model-card .primary');
  await wait("!document.querySelector('dialog.api-model-card')",'edited model saved');
  data=JSON.parse((await dispatcher.dispatch('/api/models')).body);model=data.models[0];assert.equal(model.alerts.balanceBelow,undefined);assert.equal(model.manualQuota.remaining,75);
  checks.push('editing restores advanced fields and blank alert inputs really disable the alert');
  await screenshot('feature-api-settings');
  await click('.api-model-row button:nth-of-type(4)');
  await wait("document.querySelector('dialog.api-model-card')?.open",'per-model reminder selector');
  await click('dialog.api-model-card button:first-of-type');
  await wait("window.__dshwRemindMask?.isConnected",'per-model modular reminder editor');
  assert.doesNotMatch(await ev("window.__dshwRemindMask.querySelector('.dshwv-bubprev').innerText"),/\{api_/);
  await ev("window.__dshwRemindMask.querySelector('.dshwv-bubbtn-ok').click()");
  await wait("!window.__dshwRemindMask?.isConnected",'per-model reminder save');
  await wait(`WhaleApiModels.load(true).then(data=>data.models.find(model=>model.id===${JSON.stringify(model.id)})?.bubbleSettings?.balance?.lines?.length===2)`,'per-model modules persisted');
  checks.push('each API model has reusable modular reminder layouts with resolved previews');
  await ev(`window.__whaleRenderTest.queue([{kind:'custom',modules:[{type:'quota',apiModelId:${JSON.stringify(model.id)},quotaKey:'primary',tpl:'{api_name} {quota_left_round} · {quota_reset_short}',size:4}]}]);window.__whaleRenderTest.open();`);
  await wait("document.querySelector('.dshwv-pop').innerText.includes('75%')",'custom API quota binding');
  const text=await ev("document.querySelector('.dshwv-pop').innerText");assert.doesNotMatch(text,/\{quota_/);assert.match(text,/手动/);
  checks.push('API quota bubble resolves percentage, countdown and manual source using saved configuration');
  await screenshot('feature-api-quota');await ev('window.__whaleRenderTest.close()');
  await ev("window.dispatchEvent(new Event('whale-edit-turn-cost'))");
  await wait("window.__dshwRemindMask?.isConnected",'modular turn prompt editor');
  const preview=await ev("window.__dshwRemindMask.querySelector('.dshwv-bubprev').innerText");
  assert.doesNotMatch(preview,/\{turn_/);assert.match(preview,/12[,.]?840|12\.8/);
  await screenshot('feature-turn-editor');
  await ev("window.__dshwRemindMask.querySelector('.dshwv-bubbtn-ok').click()");
  await wait("!window.__dshwRemindMask?.isConnected",'turn editor saved');
  const usage=dispatcher.whale.readUsageSettings();assert.equal(usage.turnCost.lines.length,3);assert.equal(usage.turnCost.lines[1].text,'{turn_primary}');
  checks.push('turn prompt editor uses actual preview values and writes reusable modules');
  await ev("window.dispatchEvent(new Event('whale-open-settings'))");
  await wait("document.querySelector('#settings-dialog').open",'reopen settings for removal');
  await click('.api-model-row button:nth-of-type(3)');
  await wait("document.querySelector('dialog.api-model-card')?.open",'native deletion confirmation');
  await click('dialog.api-model-card .primary');
  await wait("!document.querySelector('.api-model-row')",'model removed');
  assert.equal(JSON.parse((await dispatcher.dispatch('/api/models')).body).models.length,0);
  checks.push('model removal uses a reachable native confirmation and removes the saved record');
  return {checks};
}
